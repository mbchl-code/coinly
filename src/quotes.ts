const LAST_KEY = 'coinly:last-quote'

export function pickQuote(): Quote {
  let last = -1
  try {
    last = Number(localStorage.getItem(LAST_KEY) ?? -1)
  } catch { /* ignore */ }
  let i = Math.floor(Math.random() * QUOTES.length)
  if (i === last) i = (i + 1 + Math.floor(Math.random() * (QUOTES.length - 1))) % QUOTES.length
  try {
    localStorage.setItem(LAST_KEY, String(i))
  } catch { /* ignore */ }
  return QUOTES[i]
}

// Picked once per app launch so it stays put while switching tabs.
export const quoteOfSession = pickQuote()
